// Re-runnable: the robot's shadow shape. Voxelizes every triangle of the model (all nodes, posed as stored) into
// cubes of CELL model metres and writes one ball per occupied cube to app/src/moon/robotShape.ts:
//   [x, y, z, r, part]  model metres (+X left, +Y up, +Z front); part: 0 body, 1..6 wheel (WHEELS order), 7 panel
// The app moves the wheel balls with the wheels, the panel balls with the panel, and draws their shadows.
//   GLTF_TOOLS=<tools folder> node shadow-balls.mjs <rover-moonda.glb> <out .ts>
import { io as getIO } from './_tools.mjs';
import { writeFileSync } from 'node:fs';
const [, , src, dst] = process.argv;
const CELL = +(process.env.CELL ?? 0.17);
const doc = await (await getIO()).read(src);
const wheels = ['wheel_LF', 'wheel_LM', 'wheel_LB', 'wheel_RF', 'wheel_RM', 'wheel_RB'];
const cells = new Map();
const mul = (m, v) => [m[0] * v[0] + m[4] * v[1] + m[8] * v[2] + m[12], m[1] * v[0] + m[5] * v[1] + m[9] * v[2] + m[13], m[2] * v[0] + m[6] * v[1] + m[10] * v[2] + m[14]];
const SKIP = /^(arm|turret|hinge|Empty\.002|Armature|Bone)/; // the arm is folded by the app; small bits: ignored (tiny)
for (const node of doc.getRoot().listNodes()) {
  const mesh = node.getMesh();
  if (!mesh) continue;
  let part = 0, n = node;
  while (n) { const nm = n.getName(); const w = wheels.indexOf(nm); if (w >= 0) { part = w + 1; break; } if (/^solar_(yaw|tilt|panel)$/.test(nm)) { part = 7; break; } n = n.getParentNode(); }
  const M = node.getWorldMatrix();
  for (const p of mesh.listPrimitives()) {
    const pos = p.getAttribute('POSITION'), idx = p.getIndices()?.getArray(), v = [0, 0, 0];
    const tri = (a, b, c) => {
      // sample the triangle (corners, edges and middle) so big flat faces fill their cubes
      const P = [a, b, c].map(i => { pos.getElement(i, v); return mul(M, v); });
      const len = Math.max(...[[0, 1], [1, 2], [2, 0]].map(([i, j]) => Math.hypot(P[i][0] - P[j][0], P[i][1] - P[j][1], P[i][2] - P[j][2])));
      const k = Math.min(12, Math.ceil(len / (CELL * 0.5)));
      for (let s = 0; s <= k; s++) for (let t = 0; t <= k - s; t++) {
        const u = s / k || 0, w = t / k || 0, x = 1 - u - w;
        const q = [0, 1, 2].map(j => P[0][j] * x + P[1][j] * u + P[2][j] * w);
        const key = q.map(c => Math.floor(c / CELL)).join(',') + ',' + part;
        cells.set(key, (cells.get(key) ?? 0) + 1);
      }
    };
    if (idx) for (let t = 0; t < idx.length; t += 3) tri(idx[t], idx[t + 1], idx[t + 2]);
  }
}
const balls = [];
for (const [key] of cells) {
  const [i, j, k, part] = key.split(',').map(Number);
  if ((j + 0.5) * CELL < 0.02 && part === 0) continue;
  balls.push([+((i + 0.5) * CELL).toFixed(3), +((j + 0.5) * CELL).toFixed(3), +((k + 0.5) * CELL).toFixed(3), +(CELL * 0.62).toFixed(3), part]);
}
writeFileSync(dst, `// Generated by data-prep/rover/shadow-balls.mjs (CELL ${CELL} model m) from rover-moonda.glb: do not edit.
// The robot's shape for its shadow: [x, y, z, radius, part] in model metres (+X left, +Y up, +Z front);
// part 0 = body, 1..6 = wheel (walk.ts WHEELS order), 7 = solar panel.
export const ROBOT_SHAPE_CELL = ${CELL};
export const ROBOT_SHAPE: readonly (readonly number[])[] = ${JSON.stringify(balls)};
`);
console.log(balls.length, 'balls', [0, 1, 2, 3, 4, 5, 6, 7].map(p => balls.filter(b => b[4] === p).length).join(' '));
